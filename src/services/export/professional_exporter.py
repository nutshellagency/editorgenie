    def validate_project_data(self, timeline_data: TimelineData, clips: List[ClipData]) -> List[str]:
        """Validate project data"""
        errors = []

        # Validate timeline data
        if timeline_data.duration <= 0:
            errors.append("Timeline duration must be positive")

        if not timeline_data.resolution:
            errors.append("Timeline resolution is required")

        try:
            width, height = timeline_data.resolution.split('x')
            int(width), int(height)
        except:
            errors.append("Invalid resolution format (use WIDTHxHEIGHT)")

        # Validate clips
        if not clips:
            errors.append("At least one clip is required")

        for clip in clips:
            if clip.start_time >= clip.end_time:
                errors.append(f"Invalid clip timing for {clip.name}")

            if not clip.source_path:
                errors.append(f"Missing source path for {clip.name}")

        return errors

    def estimate_export_time(self, timeline_data: TimelineData, clips: List[ClipData],
                           settings: ProjectSettings) -> float:
        """Estimate professional export time"""
        # Base time estimate
        base_time = len(clips) * 0.1  # 100ms per clip

        # Adjust for project type
        if settings.project_type == ProjectType.PREMIERE_PRO:
            base_time *= 1.5  # Premiere projects are more complex
        elif settings.project_type == ProjectType.DAVINCI_RESOLVE:
            base_time *= 1.2  # Resolve projects are moderately complex

        # Adjust for media inclusion
        if settings.include_media:
            base_time *= 1.3  # Media organization takes time

        # Adjust for metadata preservation
        if settings.preserve_metadata:
            base_time *= 1.2  # Metadata processing takes time

        return max(base_time, 1.0)  # Minimum 1 second

    def cleanup(self):
        """Cleanup resources"""
        self.executor.shutdown(wait=True)
        self.logger.info("ProfessionalExporter cleanup completed")


